#!/usr/bin/env node
// Build Water Temple under /watertemple/ and stage it in mk7s's Cloudflare Pages site.
//
//   node scripts/publish-site-mk7s.mjs             build + copy into ../../mk7s/public/watertemple
//   node scripts/publish-site-mk7s.mjs --deploy    ...then build mk7s and deploy it with Wrangler
//
// Options: --mk7s <path> (default ../../mk7s), --branch <name> (default main, the production branch).
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    mk7s: { type: 'string' },
    deploy: { type: 'boolean', default: false },
    branch: { type: 'string', default: 'main' },
  },
});
const root = path.resolve(import.meta.dirname, '..');
const mk7s = path.resolve(root, values.mk7s ?? '../../mk7s');
const target = path.join(mk7s, 'public/watertemple');
if (
  !existsSync(path.join(mk7s, 'package.json')) ||
  JSON.parse(readFileSync(path.join(mk7s, 'package.json'), 'utf8')).name !== 'mk7s'
) {
  throw new Error(`Expected the mk7s site at ${mk7s}`);
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} failed with status ${result.status}`);
}

// Built outside the repository, so the usual dist/ (and anything previewing it) is left alone. Vite
// only: this does not typecheck, lint or test; run `npm run build` and `npm test` for that.
const output = mkdtempSync(path.join(os.tmpdir(), 'watertemple-mk7s-'));
try {
  run(
    'npx',
    ['vite', 'build', '--base', '/watertemple/', '--outDir', output, '--emptyOutDir'],
    root,
  );
  for (const page of [
    'index.html',
    'ink-orbit.html',
    'aurora.html',
    'neon-calligraphy.html',
    'dichroic-glass.html',
    'bioluminescent-currents.html',
    'liquid-chrome.html',
    'silk-embers.html',
    'eclipse-halos.html',
    'neon-mycelium.html',
    'game-of-life.html',
  ]) {
    if (!existsSync(path.join(output, page))) throw new Error(`Build is missing ${page}`);
  }
  mkdirSync(path.dirname(target), { recursive: true });
  rmSync(target, { recursive: true, force: true });
  cpSync(output, target, { recursive: true });
} finally {
  rmSync(output, { recursive: true, force: true });
}

const headersPath = path.join(mk7s, 'public/_headers');
const begin = '# BEGIN watertemple (generated by watertemple/scripts/publish-site-mk7s.mjs)';
const end = '# END watertemple';
let headers = existsSync(headersPath) ? readFileSync(headersPath, 'utf8') : '';
const first = headers.indexOf(begin);
const last = headers.indexOf(end);
if (first >= 0 && last > first)
  headers = headers.slice(0, first) + headers.slice(last + end.length);
const block = `${begin}\n/watertemple/*\n  Cache-Control: public, max-age=0, must-revalidate\n  X-Content-Type-Options: nosniff\n/watertemple/assets/*\n  ! Cache-Control\n  Cache-Control: public, max-age=31536000, immutable\n${end}`;
writeFileSync(headersPath, `${headers.trim()}\n\n${block}\n`);

const redirectsPath = path.join(mk7s, 'public/_redirects');
const redirects = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8') : '';
if (!redirects.split('\n').includes('/watertemple /watertemple/ 308'))
  writeFileSync(redirectsPath, `${redirects.trimEnd()}\n/watertemple /watertemple/ 308\n`);

console.log(`Staged ${target}; ink demo: /watertemple/ink-orbit.html`);
if (values.deploy) {
  run('npm', ['run', 'build'], mk7s);
  run(
    'npx',
    ['wrangler', 'pages', 'deploy', 'dist', '--project-name', 'mk7s', '--branch', values.branch],
    mk7s,
  );
}
