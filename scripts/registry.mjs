// Generates src/effects/registry.generated.ts: one static import per effect, replacing the
// Vite-only `import.meta.glob` registry so each effect is imported alone (M3 story 3.3).
// Run with `npm run registry`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';

const dir = 'src/effects';
const ids = readdirSync(dir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_'))
  .map((entry) => entry.name)
  .filter((id) => existsSync(`${dir}/${id}/meta.ts`) && existsSync(`${dir}/${id}/index.ts`))
  .sort();

for (const id of ids) {
  const meta = readFileSync(`${dir}/${id}/meta.ts`, 'utf8');
  if (!new RegExp(`id:\\s*'${id}'`).test(meta)) {
    throw new Error(`Effect id "${id}" must match its directory`);
  }
}

const lines = [
  '// Generated by scripts/registry.mjs. Do not edit by hand.',
  "import type { EffectMeta, EffectModule } from './types.ts';",
];
for (const [i, id] of ids.entries())
  lines.push(`import { meta as meta${i} } from './${id}/meta.ts';`);
for (const [i, id] of ids.entries()) {
  if (existsSync(`${dir}/${id}/poster.webp`))
    lines.push(`import poster${i} from './${id}/poster.webp?url';`);
}
lines.push('');
lines.push(
  `export const metas: readonly EffectMeta[] = [${ids.map((_id, i) => `meta${i}`).join(', ')}];`,
);
lines.push('');
lines.push('export const loaders: Readonly<Record<string, () => Promise<EffectModule>>> = {');
for (const id of ids)
  lines.push(`  '${id}': () => import('./${id}/index.ts').then((module) => module.effect),`);
lines.push('};');
lines.push('');
lines.push('export const posters: Readonly<Record<string, string>> = {');
for (const [i, id] of ids.entries()) {
  if (existsSync(`${dir}/${id}/poster.webp`)) lines.push(`  '${id}': poster${i},`);
}
lines.push('};');
lines.push('');

const source = await format(lines.join('\n'), {
  parser: 'typescript',
  singleQuote: true,
  printWidth: 100,
});
writeFileSync(`${dir}/registry.generated.ts`, source);
console.log(`Generated registry for ${ids.length} effects.`);
